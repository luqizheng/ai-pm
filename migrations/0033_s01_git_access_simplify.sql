-- 0033_s01_git_access_simplify: S01 · I3 V1.1 简化裁决（2026-11-04 用户裁决）。
--
-- 裁决原文：「不区分，都可以读写。因为这部分太复杂。」
-- 依据：docs/ui/smark-pm-s01-i3-git-permission-and-repo-write-authorization-v1.md
--        §0.0 V1.1 简化裁决（§0.0.3 删除项 / §0.0.4 保留项）。
--
-- 简化后的模型：
--   可访问仓库 = Task 关联仓库（delivery.task_repository）∩ 仓库状态 = verified
--   访问档位   = read_write（单一档位：可读即可写，写操作不再分级）
--
-- 因此撤下 V1.0 的「仓库级 Git 能力授权表」：
--   - 不再有逐主体、逐仓、逐操作类型的授权与撤销；
--   - 不再有依赖闭包（modify←read←commit←push）与前置校验；
--   - 不再有「调用人授权 / Project-Repository 策略」两层交集。
--
-- 保留（不简化，属访问边界而非能力分级）：
--   - 租户 / 项目隔离；
--   - Task 仓库范围（哪些仓库）；
--   - 仓库状态 = verified；
--   - Run 授权快照 + SHA-256 内容寻址（0032 的 policy_snapshot_hash 仍在用）；
--   - Project 归档门禁（I1）、Run 取消门禁。
--
-- 无回填（AGENTS.md 规则 1）：授权表自 0032 起无业务存量数据，撤下无影响。

-- ── 撤下仓库级 Git 能力授权表 ──────────────────────────────────────────
DROP TABLE IF EXISTS integration.git_capability_grant;
-- 索引 idx_git_capability_grant_principal 随表一并消失（无需单独 DROP）。
